import { readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const course=JSON.parse(await readFile('content/course.json','utf8'));
const quiz=JSON.parse(await readFile('content/quiz.json','utf8'));
const labs=JSON.parse(await readFile('content/labs.json','utf8'));
const cases=JSON.parse(await readFile('content/cases.json','utf8'));
const homework=JSON.parse(await readFile('content/homework.json','utf8'));
await rm('dist',{recursive:true,force:true});await mkdir('dist/vendor',{recursive:true});
await cp('web','dist',{recursive:true});
await cp('content/seed.sql','dist/seed.sql');
await cp('docs','dist/reference',{recursive:true});
await cp('node_modules/sql.js/dist/sql-wasm.js','dist/vendor/sql-wasm.js');
await cp('node_modules/sql.js/dist/sql-wasm.wasm','dist/vendor/sql-wasm.wasm');
await cp('node_modules/sql.js/LICENSE','dist/vendor/sql.js-LICENSE.txt');
const data=JSON.stringify({...course,quiz,labs,cases,homework}).replace(/</g,'\\u003c');
await writeFile('dist/data.js','window.COURSE_DATA = '+data+';\n');
await writeFile('dist/.nojekyll','');
const digest=createHash('sha256').update(data).digest('hex');
console.log(`Built: ${course.lessons.length} lessons, ${quiz.length} questions, ${labs.length} labs, ${cases.length} cases. Content SHA256: ${digest}`);
